// Hyper-V Report handlers
func HandleGenerateHyperVReportScript(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		http.Error(w, "Method not allowed", http.StatusMethodNotAllowed)
		return
	}

	// Read body for debugging
	bodyBytes, err := io.ReadAll(r.Body)
	if err != nil {
		http.Error(w, "Error reading request body: "+err.Error(), http.StatusBadRequest)
		return
	}

	var req models.HyperVReportRequest
	if err := json.Unmarshal(bodyBytes, &req); err != nil {
		log.Printf("Error decoding request: %v", err)
		log.Printf("Request body: %s", string(bodyBytes))
		http.Error(w, "Invalid request body: "+err.Error(), http.StatusBadRequest)
		return
	}

	log.Printf("Received request: ReportID=%v, TargetType=%s, Cluster=%s, Hosts=%v",
		req.ReportID, req.TargetType, req.Cluster, req.Hosts)

	obfuscate := true
	if req.Obfuscate != nil {
		obfuscate = *req.Obfuscate
	}
	encrypt := true
	if req.Encrypt != nil {
		encrypt = *req.Encrypt
	}

	var publicKeyPEM string
	if encrypt {
		var privateKey *rsa.PrivateKey
		var privateKeyPEMBytes []byte

		// Check if a private key already exists for this report
		if req.ReportID != nil && *req.ReportID > 0 {
			var existingPrivateKey sql.NullString
			err := database.DB.QueryRow(`
				SELECT private_key 
				FROM hyperv_reports 
				WHERE id = ?
			`, *req.ReportID).Scan(&existingPrivateKey)

			if err == nil && existingPrivateKey.Valid && existingPrivateKey.String != "" {
				// Use existing private key
				block, _ := pem.Decode([]byte(existingPrivateKey.String))
				if block != nil {
					parsedKey, err := x509.ParsePKCS1PrivateKey(block.Bytes)
					if err == nil {
						privateKey = parsedKey
						privateKeyPEMBytes = []byte(existingPrivateKey.String)
						log.Printf("Reusing existing private key for report ID %d", *req.ReportID)
					}
				}
			}
		}

		// Generate new key pair only if no valid existing key was found
		if privateKey == nil {
			var err error
			privateKey, err = rsa.GenerateKey(rand.Reader, 2048)
		if err != nil {
			http.Error(w, "Failed to generate encryption keys: "+err.Error(), http.StatusInternalServerError)
			return
		}

		// Encode private key to PEM format
			privateKeyPEMBytes = pem.EncodeToMemory(&pem.Block{
			Type:  "RSA PRIVATE KEY",
			Bytes: x509.MarshalPKCS1PrivateKey(privateKey),
		})

		// Store private key in database if report ID is provided
		if req.ReportID != nil && *req.ReportID > 0 {
			_, err = database.DB.Exec(`
				UPDATE hyperv_reports 
				SET private_key = ? 
				WHERE id = ?
			`, string(privateKeyPEMBytes), *req.ReportID)
			if err != nil {
				log.Printf("Warning: Failed to store private key: %v", err)
				}
			}
		}

		// Get public key in PEM format
		publicKeyDER, err := x509.MarshalPKIXPublicKey(&privateKey.PublicKey)
		if err != nil {
			http.Error(w, "Failed to encode public key: "+err.Error(), http.StatusInternalServerError)
			return
		}
		publicKeyPEMBytes := pem.EncodeToMemory(&pem.Block{
			Type:  "PUBLIC KEY",
			Bytes: publicKeyDER,
		})
		publicKeyPEM = string(publicKeyPEMBytes)
	}

	// Generate script with appropriate options
	script := generateHyperVReportScript(req, publicKeyPEM, encrypt)

	if obfuscate {
		script = scripts.ObfuscatePowerShellScript(script)
	}

	response := models.HyperVReportResponse{Script: script}
	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(response)
}

