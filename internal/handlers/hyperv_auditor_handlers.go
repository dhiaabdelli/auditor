func HandleGetSingleHyperVReport(w http.ResponseWriter, r *http.Request) {
	// Extract report ID from URL path
	path := strings.TrimPrefix(r.URL.Path, "/api/hyperv-reports/")
	reportID := strings.Split(path, "/")[0]

	if reportID == "" {
		http.Error(w, "Missing report ID", http.StatusBadRequest)
		return
	}

	w.Header().Set("Content-Type", "application/json")

	// Query the database for the specific report using correct column names
	var name, targetType, clusterName, hostNames, reportData, privateKey sql.NullString
	var createdAt, updatedAt string

	err := database.DB.QueryRow(`
		SELECT name, target_type, cluster_name, host_names, report_data, private_key, created_at, updated_at 
		FROM hyperv_reports 
		WHERE id = ?`, reportID).Scan(
		&name, &targetType, &clusterName, &hostNames, &reportData, &privateKey, &createdAt, &updatedAt)

	if err != nil {
		if err == sql.ErrNoRows {
			http.Error(w, "Report not found", http.StatusNotFound)
		} else {
			log.Printf("Error querying report: %v", err)
			http.Error(w, "Database error", http.StatusInternalServerError)
		}
		return
	}

	if !reportData.Valid || reportData.String == "" {
		http.Error(w, "Report data not found", http.StatusNotFound)
		return
	}

	// Try to parse as plain JSON first
	var data map[string]interface{}
	rawJSON := strings.TrimSpace(reportData.String)

	if err := json.Unmarshal([]byte(rawJSON), &data); err != nil {
		http.Error(w, "Invalid report data format", http.StatusInternalServerError)
		return
	}

	// Check if data is encrypted and decrypt if needed
	if utils.IsEncryptedPayload(data) {
		if !privateKey.Valid || privateKey.String == "" {
			http.Error(w, "Private key not found for encrypted report", http.StatusBadRequest)
			return
		}

		decryptedData, err := utils.DecryptData(rawJSON, privateKey.String)
		if err != nil {
			log.Printf("Error decrypting report data: %v", err)
			http.Error(w, "Failed to decrypt report data", http.StatusInternalServerError)
			return
		}

		// Parse decrypted data
		if err := json.Unmarshal([]byte(decryptedData), &data); err != nil {
			http.Error(w, "Invalid decrypted report data", http.StatusInternalServerError)
			return
		}
	}

	// Return the full report data (which is what the frontend expects)
	json.NewEncoder(w).Encode(data)
}

// Hyper-V Report CRUD handlers
func HandleGetHyperVReports(w http.ResponseWriter, r *http.Request) {
	// Ensure table exists
	_, err := database.DB.Exec(`
		CREATE TABLE IF NOT EXISTS hyperv_reports (
			id INTEGER PRIMARY KEY AUTOINCREMENT,
			name TEXT NOT NULL,
			target_type TEXT NOT NULL,
			cluster_name TEXT,
			host_names TEXT,
			report_data TEXT,
			private_key TEXT,
			created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
			updated_at DATETIME DEFAULT CURRENT_TIMESTAMP
		)
	`)
	if err != nil {
		log.Printf("Error creating hyperv_reports table: %v", err)
		http.Error(w, err.Error(), http.StatusInternalServerError)
		return
	}

	rows, err := database.DB.Query(`
		SELECT id, name, target_type, cluster_name, host_names, 
		       CASE WHEN report_data IS NOT NULL AND report_data != '' THEN 1 ELSE 0 END as has_data,
		       created_at, updated_at 
		FROM hyperv_reports 
		ORDER BY created_at DESC
	`)
	if err != nil {
		log.Printf("Error querying hyperv_reports: %v", err)
		http.Error(w, err.Error(), http.StatusInternalServerError)
		return
	}
	defer rows.Close()

	var reports []map[string]interface{}
	for rows.Next() {
		var id int
		var name, targetType, clusterName, hostNames sql.NullString
		var hasData int
		var createdAt, updatedAt string

		err := rows.Scan(&id, &name, &targetType, &clusterName, &hostNames, &hasData, &createdAt, &updatedAt)
		if err != nil {
			continue
		}

		report := map[string]interface{}{
			"id":         id,
			"name":       name.String,
			"targetType": targetType.String,
			"hasData":    hasData == 1,
			"createdAt":  createdAt,
			"updatedAt":  updatedAt,
		}

		if clusterName.Valid && clusterName.String != "" {
			report["clusterName"] = clusterName.String
		}
		if hostNames.Valid && hostNames.String != "" {
			report["hostNames"] = hostNames.String
		}

		reports = append(reports, report)
	}

	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(reports)
}

func HandleCreateHyperVReport(w http.ResponseWriter, r *http.Request) {
	var req models.CreateHyperVReportRequest

	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		http.Error(w, "Invalid request body", http.StatusBadRequest)
		return
	}

	if req.Name == "" {
		http.Error(w, "Report name is required", http.StatusBadRequest)
		return
	}

	var clusterName, hostNames sql.NullString
	if req.TargetType == "cluster" {
		// Use clusterName if provided, otherwise use cluster
		clusterValue := req.ClusterName
		if clusterValue == "" {
			clusterValue = req.Cluster
		}
		clusterName = sql.NullString{String: clusterValue, Valid: clusterValue != ""}
	} else {
		// Use hostNames if provided as string, otherwise join hosts array
		var hostNamesValue string
		if req.HostNames != "" {
			hostNamesValue = req.HostNames
		} else if len(req.Hosts) > 0 {
			hostNamesValue = strings.Join(req.Hosts, ",")
		}
		hostNames = sql.NullString{String: hostNamesValue, Valid: hostNamesValue != ""}
	}

	result, err := database.DB.Exec(`
		INSERT INTO hyperv_reports (name, target_type, cluster_name, host_names)
		VALUES (?, ?, ?, ?)
	`, req.Name, req.TargetType, clusterName, hostNames)

	if err != nil {
		http.Error(w, err.Error(), http.StatusInternalServerError)
		return
	}

	id, _ := result.LastInsertId()
	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(map[string]interface{}{
		"success": true,
		"id":      id,
	})
}

